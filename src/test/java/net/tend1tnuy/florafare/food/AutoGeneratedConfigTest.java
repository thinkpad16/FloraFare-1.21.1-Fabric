package net.tend1tnuy.florafare.food;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Which configs may take a food's vanilla effects away. Only an explicit one: a config
 * generated from the item's own values has no effects only because nobody wrote any,
 * and suppressing the vanilla ones on that basis stripped modded foods of their point.
 */
class AutoGeneratedConfigTest {

    private static final String TARGET = "florafare_test:auto_gen_probe";

    @AfterEach
    void cleanUp() {
        FoodBuffManager.removeConfig(TARGET);
    }

    @Test
    @DisplayName("a config nobody registered is auto-generated")
    void unregisteredIsGenerated() {
        assertTrue(FoodBuffManager.isAutoGenerated(FoodBuffData.builder(TARGET).build()));
    }

    @Test
    @DisplayName("the registered instance is explicit")
    void registeredIsExplicit() {
        FoodBuffData explicit = FoodBuffData.builder(TARGET).duration(1200).build();
        FoodBuffManager.putConfig(TARGET, explicit);
        assertFalse(FoodBuffManager.isAutoGenerated(explicit));
    }

    @Test
    @DisplayName("an equal copy is explicit too, so a config sync swapping instances changes nothing")
    void equalCopyIsExplicit() {
        FoodBuffData explicit = FoodBuffData.builder(TARGET).duration(1200).build();
        FoodBuffManager.putConfig(TARGET, explicit);
        assertFalse(FoodBuffManager.isAutoGenerated(FoodBuffData.fromNbt(explicit.toNbt())));
    }

    @Test
    @DisplayName("a different config under a registered target is not the registered one")
    void differentIsGenerated() {
        FoodBuffManager.putConfig(TARGET, FoodBuffData.builder(TARGET).duration(1200).build());
        assertTrue(FoodBuffManager.isAutoGenerated(FoodBuffData.builder(TARGET).duration(40).build()));
    }

    @Test
    @DisplayName("a /florafare setbuff stack config is always explicit")
    void stackIsExplicit() {
        assertFalse(FoodBuffManager.isAutoGenerated(FoodBuffData.builder("stack:1234").build()));
    }

    @Test
    @DisplayName("null is not a generated config")
    void nullIsNot() {
        assertFalse(FoodBuffManager.isAutoGenerated(null));
    }
}
